CREATE TABLE battle_archive (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    world_id INTEGER NOT NULL REFERENCES worlds(id) ON DELETE CASCADE,
    battle_key TEXT NOT NULL,
    player_character_id BIGINT REFERENCES characters(id) ON DELETE SET NULL,
    opponent_character_id BIGINT REFERENCES characters(id) ON DELETE SET NULL,
    player_name TEXT NOT NULL,
    opponent_name TEXT NOT NULL,
    player_level INTEGER NOT NULL CHECK (player_level >= 1),
    opponent_level INTEGER NOT NULL CHECK (opponent_level >= 1),
    winner_name TEXT NOT NULL,
    outcome TEXT NOT NULL CHECK (outcome IN ('win', 'draw', 'loss')),
    turns INTEGER NOT NULL DEFAULT 0 CHECK (turns >= 0),
    replay_json JSONB NOT NULL CHECK (jsonb_typeof(replay_json) = 'object'),
    created_at DOUBLE PRECISION NOT NULL,
    UNIQUE (world_id, battle_key)
);
CREATE INDEX battle_archive_world_created ON battle_archive(world_id, created_at DESC, id DESC);

-- Редактор карт. Каталог тайлов и объектов синхронизируется с файлами assets/map при запуске сервера.
CREATE TABLE map_catalog (
    item_key TEXT PRIMARY KEY,
    kind TEXT NOT NULL CHECK (kind IN ('ground', 'object')),
    category TEXT NOT NULL,
    asset TEXT NOT NULL,
    footprint_w INTEGER NOT NULL CHECK (footprint_w >= 1),
    footprint_h INTEGER NOT NULL CHECK (footprint_h >= 1),
    blocks BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INTEGER NOT NULL DEFAULT 0
);

-- Опубликованная карта мира: клетки, из которых строится рельеф. Миры — строки общей таблицы worlds.
CREATE TABLE map_live_cells (
    world_id INTEGER NOT NULL REFERENCES worlds(id) ON DELETE CASCADE,
    layer TEXT NOT NULL CHECK (layer IN ('ground', 'overlay', 'object')),
    x INTEGER NOT NULL CHECK (x >= 0),
    y INTEGER NOT NULL CHECK (y >= 0),
    item_key TEXT NOT NULL REFERENCES map_catalog(item_key),
    PRIMARY KEY (world_id, layer, x, y)
);

CREATE TABLE map_live_mobs (
    world_id INTEGER NOT NULL REFERENCES worlds(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    x INTEGER NOT NULL CHECK (x >= 0),
    y INTEGER NOT NULL CHECK (y >= 0),
    PRIMARY KEY (world_id, x, y)
);

CREATE TABLE map_live_spawns (
    world_id INTEGER NOT NULL REFERENCES worlds(id) ON DELETE CASCADE,
    x INTEGER NOT NULL CHECK (x >= 0),
    y INTEGER NOT NULL CHECK (y >= 0),
    PRIMARY KEY (world_id, x, y)
);

-- Сохранённые заготовки карт (общие для всех миров Колоды этой схемы), JSON-поля как в Операторе 1.
CREATE TABLE map_saved (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    mode TEXT NOT NULL DEFAULT 'kaloda',
    map_w INTEGER NOT NULL CHECK (map_w BETWEEN 16 AND 512),
    map_h INTEGER NOT NULL CHECK (map_h BETWEEN 16 AND 512),
    cells_json TEXT NOT NULL,
    mobs_json TEXT NOT NULL,
    spawns_json TEXT NOT NULL DEFAULT '[]',
    created_by BIGINT REFERENCES users(id),
    created_at DOUBLE PRECISION NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL
);

-- Сведения о карте, опубликованной в мир (одна публикация на мир); saved_id — заготовка, из которой она сделана.
CREATE TABLE map_world_publish (
    world_id INTEGER PRIMARY KEY REFERENCES worlds(id) ON DELETE CASCADE,
    name TEXT NOT NULL DEFAULT '',
    map_w INTEGER NOT NULL CHECK (map_w BETWEEN 16 AND 512),
    map_h INTEGER NOT NULL CHECK (map_h BETWEEN 16 AND 512),
    published_at DOUBLE PRECISION NOT NULL,
    mode TEXT NOT NULL DEFAULT 'kaloda',
    saved_id BIGINT REFERENCES map_saved(id) ON DELETE SET NULL
);
