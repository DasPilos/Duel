CREATE TABLE sessions (
    token TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    world_id INTEGER NOT NULL REFERENCES worlds(id),
    created_at DOUBLE PRECISION NOT NULL,
    last_seen_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX idx_sessions_user ON sessions(user_id);
CREATE INDEX idx_sessions_last_seen ON sessions(last_seen_at);

CREATE TABLE characters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    world_id INTEGER NOT NULL REFERENCES worlds(id),
    name TEXT NOT NULL,
    type TEXT NOT NULL DEFAULT 'warrior',
    level INTEGER NOT NULL DEFAULT 1,
    xp BIGINT NOT NULL DEFAULT 0,
    hp INTEGER NOT NULL,
    max_hp INTEGER NOT NULL,
    mp INTEGER NOT NULL DEFAULT 50,
    max_mp INTEGER NOT NULL DEFAULT 50,
    stats_json TEXT NOT NULL,
    stat_points INTEGER NOT NULL DEFAULT 6,
    zone TEXT NOT NULL DEFAULT 'town',
    copper BIGINT NOT NULL DEFAULT 0,
    silver BIGINT NOT NULL DEFAULT 0,
    gold BIGINT NOT NULL DEFAULT 0,
    updated_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX idx_characters_user ON characters(user_id);
CREATE INDEX idx_characters_world ON characters(world_id);
-- One player character per account in each world; NPCs (system user) are exempt.
CREATE UNIQUE INDEX uq_characters_user_world ON characters(user_id, world_id) WHERE user_id <> 0;
CREATE UNIQUE INDEX uq_characters_world_name ON characters(world_id, lower(name)) WHERE user_id <> 0;

CREATE FUNCTION forbid_character_world_change() RETURNS trigger AS $$
BEGIN
    IF NEW.world_id IS DISTINCT FROM OLD.world_id THEN
        RAISE EXCEPTION 'characters.world_id is immutable';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_characters_world_immutable
    BEFORE UPDATE OF world_id ON characters
    FOR EACH ROW EXECUTE FUNCTION forbid_character_world_change();

CREATE TABLE chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    world_id INTEGER NOT NULL REFERENCES worlds(id),
    location TEXT NOT NULL,
    sender_character_id BIGINT NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    recipient_character_id TEXT,
    text TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL,
    deleted_at DOUBLE PRECISION,
    deleted_by BIGINT
);
CREATE INDEX idx_chat_messages_location_time ON chat_messages(world_id, location, created_at, id);

CREATE TABLE chat_reads (
