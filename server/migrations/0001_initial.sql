-- Initial PostgreSQL schema (ported from the SQLite schema + multi-world support).
-- Timestamps stay as Unix epoch seconds (DOUBLE PRECISION) to match the game code.

CREATE TABLE worlds (
    id INTEGER PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'open',
    created_at DOUBLE PRECISION NOT NULL
);

