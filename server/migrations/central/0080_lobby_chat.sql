CREATE TABLE lobby_chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    text TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX idx_lobby_chat_messages_created_at ON lobby_chat_messages(created_at, id);
CREATE INDEX idx_lobby_chat_messages_sender_time ON lobby_chat_messages(sender_user_id, created_at);
