CREATE TABLE map_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    world_id INTEGER NOT NULL REFERENCES worlds(id) ON DELETE CASCADE,
    name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 64),
    created_at DOUBLE PRECISION NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL,
    UNIQUE (world_id, name)
);

CREATE TABLE map_draft_cells (
    draft_id BIGINT NOT NULL REFERENCES map_drafts(id) ON DELETE CASCADE,
    layer TEXT NOT NULL CHECK (layer IN ('ground', 'object')),
    x INTEGER NOT NULL CHECK (x >= 0),
    y INTEGER NOT NULL CHECK (y >= 0),
    item_key TEXT NOT NULL REFERENCES map_catalog(item_key),
    PRIMARY KEY (draft_id, layer, x, y)
);

ALTER TABLE map_meta ADD COLUMN draft_id BIGINT REFERENCES map_drafts(id) ON DELETE SET NULL;
